#!/usr/bin/env python3
"""Generate paw_3360/srom.h (the PMW3360 SROM firmware, 4094 bytes) from
SunjunKim's Arduino library on GitHub (LGPL-2.1).

Usage:  python3 make_srom.py
"""
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/SunjunKim/PMW3360/master/src/PMW3360.cpp"
OUT = "paw_3360/srom.h"

src = urllib.request.urlopen(URL, timeout=30).read().decode("utf-8", "replace")

m_len = re.search(r"firmware_length\s*=\s*(\d+)", src)
m_arr = re.search(r"firmware_data\[\]\s*PROGMEM\s*=\s*\{(.*?)\};", src, re.S)
if not (m_len and m_arr):
    sys.exit("Could not find firmware_length / firmware_data in the source file")

expected = int(m_len.group(1))
body = re.sub(r"//[^\n]*", "", m_arr.group(1))          # strip // comments
data = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", body)]
if len(data) != expected:
    sys.exit(f"Expected {expected} bytes, parsed {len(data)}. Not writing {OUT}")

with open(OUT, "w") as f:
    f.write("// Generated by make_srom.py from SunjunKim/PMW3360 (LGPL-2.1). Do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define SROM_LENGTH {len(data)}\n")
    f.write("#define SROM_EXPECTED_ID 0x04\n\n")
    f.write("static const uint8_t srom_data[SROM_LENGTH] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(f"0x{b:02X}" for b in data[i:i+16]) + ",\n")
    f.write("};\n")
print(f"Wrote {OUT}: {len(data)} bytes, checksum(sum) = {sum(data) & 0xFFFF:#06x}")
